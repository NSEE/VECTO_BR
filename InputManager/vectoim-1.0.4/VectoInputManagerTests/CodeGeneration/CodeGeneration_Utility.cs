    [Test]
    [Explicit("Reports property types and derived types for vehicle components. Run manually to update type report.")]
    public void Report_DataPropertyTypes_And_DerivedTypes()
    {
        var outputDir = TestUtils.OutputPath;
        using StreamWriter writer = new(Path.Combine(outputDir, "VectoObjects-Partial.cs"));

        // List of target types
        var targetTypes = new[]
        {
                typeof(EngineComponentDeclarationType_v2_0),
                typeof(GearboxComponentDeclarationType_v2_0),
                typeof(TorqueConverterComponentDeclarationType_v2_0),
                typeof(RetarderComponentDeclarationType_v2_0),
                typeof(ADCComponentDeclarationType_v2_3),
                typeof(AngledriveComponentDeclarationType_v2_0),
                typeof(AxlegearComponentDeclarationType_v2_0),
                typeof(AirDragComponentDeclarationType_v2_0),
                typeof(TyreComponentDeclarationType_v2_0),
                typeof(ElectricMachineSystemComponentDeclarationType_v2_3),
                typeof(IEPCComponentDeclarationType_v2_3),
                typeof(BatteryComponentDeclarationType_v2_3),
                typeof(CapacitorSystemComponentDeclarationType_v2_3),
                typeof(FuelCellComponentDeclarationType_v2_6),

                // Not in Vehicle
                 typeof(REESSBatteryTypeREESS_v2_4),
                 typeof(REESSCapacitorType_v2_4),
                 typeof(REESSComponentDeclarationType_v2_3),
            };

        var xmlDeclAssembly = typeof(EngineComponentDeclarationType_v2_0).Assembly;

        foreach (var type in targetTypes)
        {
            writer.WriteLine("/// <summary>");
            writer.WriteLine("/// " + type.FullName);

            var dataProp = type.GetProperty("Data", BindingFlags.Public | BindingFlags.Instance);
            if (dataProp == null)
            {
                writer.WriteLine($"/// {type.Name}: No public Data property found.");
                continue;
            }

            var dataType = dataProp.PropertyType;
            TestContext.Out.WriteLine($"{type.Name}.Data: {dataType.FullName}");

            // Find all types in the assembly that inherit from dataType (excluding the base type itself)
            var derivedTypes = xmlDeclAssembly.GetTypes()
                .Where(t => t != dataType && dataType.IsAssignableFrom(t))
                .OrderBy(t => t.FullName)
                .ToList();

            if (derivedTypes.Count == 0)
            {
                writer.WriteLine($"///  No types inherit from {dataType.Name}");
            }
            else
            {
                writer.WriteLine($"///  Types inheriting from {dataType.Name}:");
                foreach (var dt in derivedTypes)
                    writer.WriteLine($"///    {dt.FullName}");
            }

            writer.WriteLine("/// </summary>");
        }
    }

    [Test]
    [Explicit("Generates a Markdown file with help text for the CLI commands. Run manually to update help outputs.")]
    public void Generate_CliHelp_Markdown()
    {
        var sections = new List<(string Title, string[] Args)>
         {
             ("vectoim job", new [] { "job", "-h" }),
             ("vectoim comp", new [] { "comp", "-h" }),
             ("vectoim sv", new [] { "sv", "-h" }),
         };

        var sb = new StringBuilder();
        sb.AppendLine("## Command Reference");
        sb.AppendLine();

        foreach (var (title, args) in sections)
        {
            var help = RunCliAndCapture(args);
            help = help.Replace("\r\n", "\n").Replace("\r", "\n");

            sb.AppendLine($"### {title}");
            sb.AppendLine();
            sb.AppendLine("```text");
            sb.AppendLine(help.TrimEnd());
            sb.AppendLine("```");
            sb.AppendLine();
        }

        var outFile = Path.Combine(VectoInputManager.Tests.TestUtils.OutputPath, "README.md");
        File.WriteAllText(outFile, sb.ToString());

        // Internal method to run the CLI and capture output using TestConsole

        string RunCliAndCapture(string[] args)
        {
            var console = new TestConsole();
            console.Width(100);

            var services = new ServiceCollection();
            VectoInputManager.Commands.ServiceCollectionExtensions.ConfigureServices(services);

            var app = new CommandApp(new VectoInputManager.Commands.TypeRegistrar(services));
            app.Configure(config =>
            {
                config.SetApplicationName("vectoim");
                config.SetApplicationVersion(VectoInputManager.Core.Consts.AppVersion);
                config.ConfigureConsole(console);
                VectoInputManager.Commands.ConsoleConfiguratorExtensions.ConfigureProgramCommands(config);
            });

            app.Run(args);
            return console.Output;
        }
    }

