    [Test]
    [Explicit("Generates JSON schema files. Run manually to update schema outputs.")]
    public void GenerateJSONSchemas()
    {
        var outputFolder = TestUtils.CombinePath(TestUtils.OutputPath, "InputSchemas");

        foreach (var componentType in Components.ComponentInformation)
        {
            TestUtils.InitGeneration();
            JSchemaGenerator generator = new();
            generator.GenerationProviders.Add(new StringEnumGenerationProvider());

            JSchema schema = generator.Generate(componentType.InputType);

            // Modify the Component property to only include the specific enum value
            if (schema.Properties != null 
                && schema.Properties.TryGetValue("Component", out JSchema? componentProperty))
            {
                componentProperty.Enum.Clear();
                componentProperty.Enum.Add(componentType.ComponentType.ToString());
            }

            var schemaFile = Path.Combine(outputFolder, componentType.ComponentType + ".schema.json");
            var content = schema.ToString().Replace("\r\n", "\n").Replace("\r", "\n");
            File.WriteAllText(schemaFile, content);
        }

        outputFolder = TestUtils.CombinePath(TestUtils.OutputPath, "VehicleSchemas");

        var types = TypeUtils.GetAllVehicleTypes();
        foreach (var type in types)
        {
            var schemaFile = Path.Combine(outputFolder, type.Name + ".schema.json");
            var s = CodeGeneration.JsonSchemaGenerator.GenerateSchema(type);
            var content = s.Replace("\r\n", "\n").Replace("\r", "\n");
            File.WriteAllText(schemaFile, content);
        }

        outputFolder = TestUtils.CombinePath(TestUtils.OutputPath, "ComponentSchemas");

        types = TypeUtils.GetAllComponentDeclarationTypes();
        foreach (var type in types)
        {
            var schemaFile = Path.Combine(outputFolder, type.Name + ".schema.json");
            var s = CodeGeneration.JsonSchemaGenerator.GenerateSchema(type);
            var content = s.Replace("\r\n", "\n").Replace("\r", "\n");
            File.WriteAllText(schemaFile, content);
        }
    }

    [Test]
    [Explicit("Generates a CSV of vehicle types. Run manually to update vehicle type data.")]
    public void GenerateVehicleTypesData_Utility()
    {
        var data = Data.GetVehicleTypes();
        var types = TypeUtils.GetAllVehicleTypes();

        using StreamWriter writer = new(Path.Combine(
            TestUtils.OutputPath, "VehicleTypes.csv"));

        writer.WriteLine("TypeName,Version,Description,Code");

        foreach (var type in types.OrderBy(c => c.Name))
        {
            var attr = type.GetCustomAttribute<XmlTypeAttribute>(false);
            var version = attr!.Namespace!.Split(":").Last();

            var desc = data.FirstOrDefault(d => d.TypeName == type.Name)?.Description ?? "Unknown";
            var code = data.FirstOrDefault(d => d.TypeName == type.Name)?.Code ?? "Unknown";

            writer.WriteLine($"{type.Name},{version},{desc},{code}");
        }
    }

