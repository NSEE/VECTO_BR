using System;
using VectoObjects;

namespace VectoInputManager.Core
{
    /// <summary>
    /// Abstract base class for standard values calculators. Each component type has a concrete
    /// implementation that calculates standard values based on user-provided input parameters.
    /// </summary>
    public abstract class BaseStandardValues
    {
        /// <summary>
        /// Calculates and generates a complete component declaration with standard values
        /// based on the provided input data.
        /// </summary>
        /// <param name="inputData">The user-provided input parameters.</param>
        /// <returns>A fully populated component declaration.</returns>
        public abstract IComponentDeclaration Calculate(BaseInput inputData);

        /// <summary>
        /// Creates a new input data object for this component type with default values.
        /// </summary>
        /// <returns>A new BaseInput instance for this component type.</returns>
        public abstract BaseInput CreateInput();

        /// <summary>
        /// Sets the calculated component into the appropriate property of a VectoInputDeclaration.
        /// </summary>
        /// <param name="vInputDeclaration">The target declaration container.</param>
        /// <param name="sv">The component to set (typically generated by Calculate method).</param>
        public abstract void SetInput(VectoInputDeclaration_v2_2 vInputDeclaration, IComponentDeclaration sv);
    }
}